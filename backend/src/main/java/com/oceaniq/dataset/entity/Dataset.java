package com.oceaniq.dataset.entity;

import com.oceaniq.user.entity.User;
import com.oceaniq.dataset.enums.DatasetStatus;
import com.oceaniq.region.entity.Region;
import com.oceaniq.species.entity.Species;


import jakarta.persistence.*;
import lombok.AllArgsConstructor;
import lombok.Setter;
import lombok.Getter;
import lombok.NoArgsConstructor;
import org.hibernate.annotations.CreationTimestamp;
import org.hibernate.annotations.UpdateTimestamp;

import java.time.LocalDate;
import java.time.LocalDateTime;
import java.util.Set;

/**
 * Entity representing a dataset uploaded by users (maps to 'datasets' table in database)
 * contains metadata about the dataset such as name, description, uploader, upload date etc... 
*/
@Entity
@Table(name = "datasets")
@Setter
@Getter
@NoArgsConstructor
@AllArgsConstructor
public class Dataset {
    
    // primary key automatically generated by database
    @Id
    @GeneratedValue(strategy = GenerationType.IDENTITY)
    private Long id;
    
    // name of dataset (max length 200 chars / cannot be null)
    @Column(nullable = false, length = 200)
    private String name;
    
    // description of dataset (can be null, stored as TEXT in database for longer content)
    @Column(columnDefinition = "TEXT")
    private String description;
    
    /**
    * many-to-one relationship with User entity (many datasets --> one user)
    * fetch type LAZY - user data is only loaded from database when accessed (improves performance when loading datasets without needing uploader data)
    * join column 'uploader_id' in datasets table references id in users table (foreign key constraint)
    */
    @ManyToOne(fetch = FetchType.LAZY)
    @JoinColumn(name = "uploader_id", nullable = false)
    private User uploader;
    
    // date when dataset was uploaded (cannot be null)
    @Column(nullable = false)
    private LocalDate uploadDate;
    
    // size of dataset file in bytes (cannot be null)
    @Column(nullable = false)
    private Long fileSize; 
    
    // URL or path to dataset file (cannot be null)
    @Column(nullable = false)
    private String fileUrl;
    
    // status of dataset (stored as string using DatasetStatus enum, defaults to PENDING)
    @Enumerated(EnumType.STRING)
    @Column(nullable = false)
    private DatasetStatus status = DatasetStatus.PENDING;
    
    // category of dataset (max length 100 chars)
    @Column(length = 100)
    private String category;
    
    /**
     * region (location) associated with dataset (max length 100 chars)
     * many-to-one relationship with Region entity (many datasets --> one region)
     * fetch type LAZY - region data is only loaded from database when accessed 
     */
    @ManyToOne(fetch = FetchType.LAZY)
    @JoinColumn(name = "region_id")
    private Region region;

    /**
     * many-to-many relationship with Species entity (many datasets --> many species)
     * join table 'dataset_species' with foreign keys 'dataset_id' and 'species_id
     * inverse join column 'species_id' references id in species table (foreign key constraint)
    */
    @ManyToMany
    @JoinTable(
        name = "dataset_species",
        joinColumns = @JoinColumn(name = "dataset_id"),
        inverseJoinColumns = @JoinColumn(name = "species_id")
    )
    // this join table stores the many-to-many links between datasets and species
    private Set<Species> species;
    
    // number of times dataset has been downloaded (cannot be null, defaults to 0)
    @Column(nullable = false)
    private Integer downloadCount = 0;
    
    // timestamp when dataset record was created (automatically set by database, cannot be null, not updatable)
    @CreationTimestamp
    @Column(nullable = false, updatable = false)
    private LocalDateTime createdAt;
    
    // timestamp when dataset record was last updated (automatically updated by database whenever record is modified)
    @UpdateTimestamp
    private LocalDateTime updatedAt;
    
}
